def emit_csr_params(csrs, csr_slots):
    lines = []
    csr_count = 1 << (len(csr_slots) - 1).bit_length()
    lines.append(f"  localparam int unsigned CSR_COUNT = {csr_count};")
    lines.append("")
    for c in csrs:
        addr = c.get("addr", c.get("id"))
        lines.append(f"  localparam logic [11:0] CSR_{c['name'].upper():<12} = 12'h{addr:03X};")
    lines.append("")
    for idx, name in enumerate(csr_slots):
        lines.append(f"  localparam logic [$clog2(CSR_COUNT)-1:0] CSR_SLOT_{name.upper():<12} = {idx};")
    return "\n".join(lines) + "\n\n"


def emit_mtvec_params(mtvec_modes):
    width = mtvec_modes["width"]
    lines = []
    for name, value in mtvec_modes["values"].items():
        lines.append(
            f"  localparam logic [{width - 1}:0] "
            f"MTVEC_MODE_{name.upper()} = {width}'b{value:0{width}b};"
        )
    lines.append("")
    lines.extend([
        "  function automatic logic [XLEN-1:0] trap_vector_addr(",
        "      input logic [XLEN-1:0] mtvec,",
        "      input logic [XLEN-1:0] mcause",
        "  );",
        "    logic [XLEN-1:0] base;",
        "    logic [XLEN-1:0] cause_offset;",
        "",
        "    base         = {mtvec[XLEN-1:2], 2'b00};",
        "    cause_offset = {mcause[XLEN-3:0], 2'b00};",
        "",
        "    if (mtvec[1:0] == MTVEC_MODE_VECTORED && mcause[XLEN-1]) begin",
        "      return base + cause_offset;",
        "    end",
        "    return base;",
        "  endfunction",
    ])
    return "\n".join(lines) + "\n\n"


