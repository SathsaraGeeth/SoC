def emit_opcode_enum(opcodes):
    lines = ["  typedef enum logic [OPCODE_W-1:0] {"]
    items = list(opcodes.items())
    for i, (name, val) in enumerate(items):
        comma = "," if i < len(items) - 1 else ""
        lines.append(f"    OP_{name:<12} = 7'b{val:07b}{comma}")
    lines.append("  } opcode_e;\n")
    return "\n".join(lines) + "\n"


