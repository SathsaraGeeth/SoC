def sv_const_name(mnemonic):
    return "INST_" + mnemonic.upper().replace(".", "_")


def emit_decode_params(params):
    lines = []
    for p in params:
        name  = sv_const_name(p["mnemonic"])
        opval = p.get("opcode_val", 0)
        f3    = p.get("funct3")
        f6    = p.get("funct6")
        f7    = p.get("funct7")
        f5    = p.get("funct5")
        aq    = p.get("aq_bit26")
        rl    = p.get("rl_bit25")
        imm   = p.get("imm_fixed")
        rs2f  = p.get("rs2_fixed")
        lines.append(f"  // {name}")
        lines.append(f"  localparam logic [6:0]  {name}_OP = 7'b{opval:07b};")

        if f3 is not None:
            lines.append(f"  localparam logic [2:0]  {name}_F3 = 3'b{f3:03b};")
        if f6 is not None:
            lines.append(f"  localparam logic [5:0]  {name}_F6 = 6'b{f6:06b};")
        if f7 is not None:
            lines.append(f"  localparam logic [6:0]  {name}_F7 = 7'b{f7:07b};")
        if f5 is not None:
            lines.append(f"  localparam logic [4:0]  {name}_F5 = 5'b{f5:05b};")
        if aq is not None:
            lines.append(f"  localparam logic        {name}_AQ = 1'b{aq};")
        if rl is not None:
            lines.append(f"  localparam logic        {name}_RL = 1'b{rl};")
        if imm is not None:
            lines.append(f"  localparam logic [11:0] {name}_IMM = 12'b{imm:012b};")
        if rs2f is not None:
            lines.append(f"  localparam logic [4:0]  {name}_RS2 = 5'b{rs2f:05b};")
        lines.append("")

    return "\n".join(lines) + "\n"


