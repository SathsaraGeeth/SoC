def mnemonic_enum_name(mnemonic):
    return "M_" + mnemonic.upper().replace(".", "_")


def emit_mnemonic_enum(params):
    names = [mnemonic_enum_name(p["mnemonic"]) for p in params] + ["M_INVALID"]
    width = len(names)
    lines = [f"  typedef enum logic [$clog2({width})-1:0] {{"]
    for i, n in enumerate(names):
        comma = "," if i < len(names) - 1 else ""
        lines.append(f"    {n}{comma}")
    lines.append("  } mnemonic_e;\n")
    return "\n".join(lines) + "\n"


def emit_trap_cause_params(trap_causes, interrupt_causes):
    lines = []
    for name, value in trap_causes["values"].items():
        lines.append(
            f"  localparam logic [TRAP_CAUSE_W-1:0] "
            f"TRAP_CAUSE_{name.upper()} = TRAP_CAUSE_W'({value});"
        )
    lines.append("")
    for name, value in interrupt_causes.items():
        lines.append(
            f"  localparam logic [TRAP_CAUSE_W-1:0] "
            f"IRQ_CAUSE_{name.upper()} = "
            f"{{1'b1, TRAP_CAUSE_CODE_W'({value})}};"
        )
    return "\n".join(lines) + "\n\n"


# ---------------------------------------------------------------------------
# decode function
# Keying strategy:
#   R / R4         : {op[6:0], f3[2:0], f7[6:0]}
#   I (shift)      : {op[6:0], f3[2:0], f7[6:0]}   (f7 is imm[11:5])
#   I (other)      : {op[6:0], f3[2:0], 7'b???????}
#   CVT/FSQRT      : {op[6:0], f3[2:0], f7[6:0]}  but rs2_fixed disambiguates
#                    → emit  {op, f3, f7, rs2_fixed} with 22-bit key
#   B / S          : {op[6:0], f3[2:0], 7'b???????}
#   U / J          : {op[6:0], 3'b???, 7'b???????}
#   FENCE.i        : funct3=001 I-format, wildcard f7
#   FENCE.d.*      : funct3=000 I-format, use imm_bits in [31:20]
#                    → keep simple, wildcard f7 (fence variants are NOP at uarch)
# We use a 22-bit key: {op[6:0], f3[2:0], f7/rs2_combo[6:0], rs2[4:0]}
# For most instructions rs2 field is wildcard.
# ---------------------------------------------------------------------------

def decode_key(p):
    op_s, f3_s, f7_s, rs2_s = decode_key_parts(p)
    return f"{{{op_s}, {f3_s}, {f7_s}, {rs2_s}}}"


def decode_key_parts(p):
    opval = p.get("opcode_val", 0)
    fmt   = p.get("format", "R")
    f3    = p.get("funct3")
    f6    = p.get("funct6")
    f7    = p.get("funct7")
    f5    = p.get("funct5")
    aq    = p.get("aq_bit26")
    rl    = p.get("rl_bit25")
    imm   = p.get("imm_fixed")
    rs2f  = p.get("rs2_fixed")
    mn    = p.get("mnemonic", "")

    op_s  = f"7'b{opval:07b}"
    f3_s  = f"3'b{f3:03b}" if f3 is not None else "3'b???"
    f7_s  = f"7'b{f7:07b}" if f7 is not None else "7'b???????"
    rs2_s = f"5'b{rs2f:05b}" if rs2f is not None else "5'b?????"

    if f5 is not None:
        aq_s = str(aq) if aq is not None else "?"
        rl_s = str(rl) if rl is not None else "?"
        f7_s = f"7'b{f5:05b}{aq_s}{rl_s}"

    if f6 is not None:
        f7_s = f"7'b{f6:06b}?"

    # For J and U formats, f3 and f7 don't exist
    if fmt in ("J", "U"):
        f3_s = "3'b???"
        f7_s = "7'b???????"
        rs2_s = "5'b?????"

    # RV64 I-format shifts encode funct6 in imm[11:6]; shamt[5] is variable.
    # RV32 I-format shifts encode funct7 in imm[11:5].
    if fmt == "I" and f7 is not None:
        f7_s = f"7'b{f7:07b}"

    # I-format system instructions use imm[11:0] for the full operation.
    if fmt == "I" and imm is not None:
        f7_s  = f"7'b{(imm >> 5) & 0x7f:07b}"
        rs2_s = f"5'b{imm & 0x1f:05b}"

    # R4: f7 field is rs3[4:0]++funct2[1:0]; use wildcard (rs3 is data, funct2 is type)
    if fmt == "R4":
        f7_s = "7'b???????"

    return op_s, f3_s, f7_s, rs2_s


def emit_decode_function(params):
    op_groups = {}
    for p in params:
        op_s, f3_s, f7_s, rs2_s = decode_key_parts(p)
        op_groups.setdefault(op_s, []).append((p, f3_s, f7_s, rs2_s))

    lines = []
    lines.append("  function automatic mnemonic_e decode(input logic [INST_W-1:0] inst);")
    lines.append("    logic [6:0] op;")
    lines.append("    logic [2:0] f3;")
    lines.append("    logic [6:0] f7;")
    lines.append("    logic [4:0] rs2;")
    lines.append("    op  = inst[6:0];")
    lines.append("    f3  = inst[14:12];")
    lines.append("    f7  = inst[31:25];")
    lines.append("    rs2 = inst[24:20];")
    lines.append("    decode = M_INVALID;")
    lines.append("    unique case (op)")

    for op_s in sorted(op_groups.keys()):
        entries = op_groups[op_s]
        f3_groups = {}
        for p, f3_s, f7_s, rs2_s in entries:
            f3_groups.setdefault(f3_s, []).append((p, f7_s, rs2_s))

        lines.append(f"      {op_s}: begin")
        if len(entries) == 1:
            p, _f3_s, _f7_s, _rs2_s = entries[0]
            lines.append(f"        decode = {mnemonic_enum_name(p['mnemonic'])};")
        else:
            lines.append("        casez (f3)")
            for f3_s in sorted(f3_groups.keys()):
                seen_f7_rs2 = set()
                f7_entries = []
                for p, f7_s, rs2_s in f3_groups[f3_s]:
                    key = (f7_s, rs2_s)
                    if key in seen_f7_rs2:
                        continue
                    seen_f7_rs2.add(key)
                    f7_entries.append((p, f7_s, rs2_s))
                lines.append(f"          {f3_s}: begin")
                if len(f7_entries) == 1:
                    p, f7_s, rs2_s = f7_entries[0]
                    if f7_s == "7'b???????" and rs2_s == "5'b?????":
                        lines.append(f"            decode = {mnemonic_enum_name(p['mnemonic'])};")
                    else:
                        mn = mnemonic_enum_name(p["mnemonic"])
                        lines.append("            casez ({f7, rs2})")
                        lines.append(f"              {{{f7_s}, {rs2_s}}}: decode = {mn};")
                        lines.append("              default: decode = M_INVALID;")
                        lines.append("            endcase")
                else:
                    lines.append("            casez ({f7, rs2})")
                    for p, f7_s, rs2_s in f7_entries:
                        mn = mnemonic_enum_name(p["mnemonic"])
                        lines.append(f"              {{{f7_s}, {rs2_s}}}: decode = {mn};")
                    lines.append("              default: decode = M_INVALID;")
                    lines.append("            endcase")
                lines.append("          end")
            lines.append("          default: decode = M_INVALID;")
            lines.append("        endcase")
        lines.append("      end")

    lines.append("      default: decode = M_INVALID;")
    lines.append("    endcase")
    lines.append("  endfunction\n")
    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------------------
# operation enums (alu_op_e, fpu_op_e, ls_op_e, ...)
# ---------------------------------------------------------------------------


def emit_op_enums(op_enums):
    out = []
    for name, spec in op_enums.items():
        width = spec["width"]
        values = spec["values"]
        enum_type = f"{name}_e"
        lines = [f"  typedef enum logic [{width-1}:0] {{"]
        for i, v in enumerate(values):
            comma = "," if i < len(values) - 1 else ""
            lines.append(f"    {v}{comma}")
        lines.append(f"  }} {enum_type};\n")
        out.append("\n".join(lines) + "\n")

    return "\n".join(out)


# ---------------------------------------------------------------------------
# register aliases
# ---------------------------------------------------------------------------


def emit_reg_aliases():
    lines = ["  // Register indices"]
    for i in range(32):
        lines.append(f"  localparam logic [4:0] X{i:<2} = 5'd{i};")
    return "\n".join(lines) + "\n\n"


