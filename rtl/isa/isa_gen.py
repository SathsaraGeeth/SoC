def main():
    base = Path(__file__).resolve().parent
    src = base / "isa.yaml"
    dst = base / "isa_pkg.sv"
    c_dst = base / "isa_generated.h"

    with open(src) as f:
        isa = yaml.safe_load(f)

    meta     = isa["meta"]
    opcodes  = isa["opcodes"]
    groups   = isa["groups"]
    csrs      = isa["csrs"]
    csr_slots = isa["csr_slots"]
    mtvec_modes = isa["mtvec_modes"]
    trap_causes = isa["trap_causes"]
    interrupt_causes = isa["interrupt_causes"]
    op_enums  = isa.get("op_enums", {})

    params = collect_decode_params(groups, opcodes)

    out = []
    out.append(emit_header(meta["xlen"], meta["reg_count"]))

    out.append(emit_section("INSTRUCTION FIELD HELPERS"))
    out.append(emit_inst_helpers(meta["inst_width"], trap_causes["width"]))

    out.append(emit_section("OPCODE ENCODING  [6:0]"))
    out.append(emit_opcode_enum(opcodes))

    out.append(emit_section("INSTRUCTION FORMATS"))
    out.append(emit_formats())

    out.append(emit_section("INSTRUCTION UNION"))
    out.append(emit_inst_union())

    out.append(emit_section("REGISTER FILE INDICES"))
    out.append(emit_reg_aliases())

    out.append(emit_section("CSR ADDRESSES"))
    out.append(emit_csr_params(csrs, csr_slots))

    out.append(emit_section("MTVEC ENCODING"))
    out.append(emit_mtvec_params(mtvec_modes))

    out.append(emit_section("TRAP CAUSE ENCODING"))
    out.append(emit_trap_cause_params(trap_causes, interrupt_causes))

    out.append(emit_section("PRIVILEGE AND CSR FIELD ENCODING"))
    out.append(emit_privilege_params())

    out.append(emit_section("PER-INSTRUCTION DECODE PARAMETERS"))
    out.append(emit_decode_params(params))

    if op_enums:
        out.append(emit_section("DECODED INSTRUCTION OPERATION ENUMS"))
        out.append(emit_op_enums(op_enums))

    out.append(emit_section("MNEMONIC ENUM"))
    out.append(emit_mnemonic_enum(params))

    out.append(emit_section("DECODE FUNCTION  key = {op[6:0], f3[2:0], f7[6:0], rs2[4:0]}"))
    out.append(emit_decode_function(params))

    out.append(emit_footer())

    with open(dst, "w") as f:
        f.write("".join(out))

    with open(c_dst, "w") as f:
        f.write(emit_c_header(isa, params))

    print(f"wrote {dst} and {c_dst} ({len(params)} instruction variants)")


if __name__ == "__main__":
    main()
