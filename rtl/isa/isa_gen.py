INHERITABLE_FIELDS = (
    "opcode",
    "format",
    "funct3",
    "funct6",
    "funct7",
    "funct5",
    "aq_bit26",
    "rl_bit25",
    "funct2",
    "rs2_fixed",
    "rs1_fixed",
    "rd_fixed",
    "imm_fixed",
)


def collect_decode_params(groups, opcodes):
    params = []

    def walk(node, inherited):
        if not isinstance(node, dict):
            return

        if "mnemonic" in node or "variants" in node:
            base = dict(inherited)
            for k in INHERITABLE_FIELDS:
                if k in node:
                    base[k] = node[k]

            variants = node.get("variants", [node] if "mnemonic" in node else [])
            for v in variants:
                entry = dict(base)
                entry.update(v)
                if "opcode" in entry:
                    raw = entry["opcode"]
                    entry["opcode_val"] = resolve_opcode(raw, opcodes)
                params.append(entry)
        else:
            inh2 = dict(inherited)
            for k in INHERITABLE_FIELDS:
                if k in node:
                    inh2[k] = node[k]

            for child in node.values():
                if isinstance(child, dict):
                    walk(child, inh2)

    for group_name, group in groups.items():
        before = len(params)
        walk(group, {})
        for entry in params[before:]:
            entry["group"] = group_name

    return params


