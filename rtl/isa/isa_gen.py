def c_name(value):
    """Return a stable C identifier for a YAML name."""
    return "".join(ch if ch.isalnum() else "_" for ch in value.upper())


def bit_mask(msb, lsb):
    return ((1 << (msb - lsb + 1)) - 1) << lsb


def add_bits(mask, match, msb, lsb, value):
    field_mask = bit_mask(msb, lsb)
    return mask | field_mask, (match & ~field_mask) | ((value << lsb) & field_mask)


def instruction_mask_match(param, fields, formats):
    """Build the exact mask/match pair described by an instruction entry."""
    mask = match = 0

    def add_field(name, value):
        nonlocal mask, match
        msb, lsb = fields[name]["bits"]
        mask, match = add_bits(mask, match, msb, lsb, value)

    add_field("opcode", param["opcode_val"])
    for name in ("funct3", "funct6", "funct7", "funct2"):
        if name in param:
            add_field(name, param[name])

    if "funct5" in param:
        mask, match = add_bits(mask, match, 31, 27, param["funct5"])
    if "aq_bit26" in param:
        mask, match = add_bits(mask, match, 26, 26, param["aq_bit26"])
    if "rl_bit25" in param:
        mask, match = add_bits(mask, match, 25, 25, param["rl_bit25"])
    for key, field in (("rd_fixed", "rd"), ("rs1_fixed", "rs1"),
                       ("rs2_fixed", "rs2")):
        if key in param:
            add_field(field, param[key])

    # I immediates are contiguous.  This also distinguishes system encodings.
    if "imm_fixed" in param:
        msb, lsb = formats[param["format"]]["imm"]["bits"]
        mask, match = add_bits(mask, match, msb, lsb, param["imm_fixed"])

    # Fence predecessor/successor bits occupy the low eight immediate bits.
    if "imm_bits" in param:
        imm_lsb = formats[param["format"]]["imm"]["bits"][1]
        mask, match = add_bits(mask, match, imm_lsb + 7, imm_lsb,
                               param["imm_bits"])
    return mask, match


def emit_c_header(isa, params):
    meta, fields, formats = isa["meta"], isa["fields"], isa["formats"]
    csr_slots = isa["csr_slots"]
    csr_count = 1 << (len(csr_slots) - 1).bit_length()
    lines = [
        "/* Generated by rtl/isa/isa_gen.py.  Do not edit. */",
        "#ifndef DMCTP_ISA_GENERATED_H",
        "#define DMCTP_ISA_GENERATED_H",
        "",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        f"#define DMCTP_XLEN {meta['xlen']}u",
        f"#define DMCTP_REG_COUNT {meta['reg_count']}u",
        f"#define DMCTP_CSR_COUNT {csr_count}u",
        f"#define DMCTP_INST_WIDTH {meta['inst_width']}u",
        f"#define DMCTP_X0_HARDWIRED_ZERO {1 if meta.get('x0_hardwired_zero') else 0}",
        "",
    ]
    for name, spec in fields.items():
        msb, lsb = spec["bits"]
        lines += [f"#define DMCTP_FIELD_{c_name(name)}_LSB {lsb}u",
                  f"#define DMCTP_FIELD_{c_name(name)}_WIDTH {msb-lsb+1}u"]
    lines += ["", "typedef enum dmctp_format {"]
    for index, name in enumerate(formats):
        lines.append(f"    DMCTP_FMT_{c_name(name)} = {index},")
    lines += ["} dmctp_format_t;", "", "typedef enum dmctp_group {"]
    group_names = list(dict.fromkeys(p["group"] for p in params))
    for index, name in enumerate(group_names):
        lines.append(f"    DMCTP_GROUP_{c_name(name)} = {index},")
    lines += ["} dmctp_group_t;", "", "typedef enum dmctp_mnemonic {"]
    for index, p in enumerate(params):
        lines.append(f"    DMCTP_M_{c_name(p['mnemonic'])} = {index},")
    lines += [f"    DMCTP_M_INVALID = {len(params)}", "} dmctp_mnemonic_t;", ""]

    for csr in isa["csrs"]:
        lines.append(f"#define DMCTP_CSR_{c_name(csr['name'])} UINT32_C(0x{csr.get('addr', csr.get('id')):03x})")
    lines.append("")
    for index, name in enumerate(csr_slots):
        lines.append(f"#define DMCTP_CSR_SLOT_{c_name(name)} {index}u")
    lines += ["", "static inline size_t dmctp_csr_slot(uint32_t address)",
              "{", "    switch (address) {"]
    csr_names = {csr["name"] for csr in isa["csrs"]}
    for name in csr_slots:
        if name in csr_names:
            cn = c_name(name)
            lines.append(f"    case DMCTP_CSR_{cn}: return DMCTP_CSR_SLOT_{cn};")
    lines += ["    default: return DMCTP_CSR_COUNT;", "    }", "}",
              "", "typedef struct dmctp_instruction_desc {",
              "    dmctp_mnemonic_t mnemonic;", "    dmctp_format_t format;",
              "    dmctp_group_t group;",
              "    uint32_t mask;", "    uint32_t match;", "    const char *name;",
              "} dmctp_instruction_desc_t;", "",
              "static const dmctp_instruction_desc_t dmctp_instruction_table[] = {"]
    for p in params:
        mask, match = instruction_mask_match(p, fields, formats)
        lines.append("    { DMCTP_M_%s, DMCTP_FMT_%s, DMCTP_GROUP_%s, UINT32_C(0x%08x), UINT32_C(0x%08x), \"%s\" }," %
                     (c_name(p["mnemonic"]), c_name(p["format"]), c_name(p["group"]), mask, match,
                      p["mnemonic"]))
    lines += ["};", "",
              "#define DMCTP_INSTRUCTION_COUNT (sizeof(dmctp_instruction_table) / sizeof(dmctp_instruction_table[0]))",
              "",
              "static inline uint32_t dmctp_field(uint32_t inst, unsigned lsb, unsigned width)",
              "{", "    return (inst >> lsb) & (uint32_t)((UINT64_C(1) << width) - 1u);", "}", ""]
    for name in fields:
        cn = c_name(name)
        lines += [f"static inline uint32_t dmctp_inst_{name}(uint32_t inst)", "{",
                  f"    return dmctp_field(inst, DMCTP_FIELD_{cn}_LSB, DMCTP_FIELD_{cn}_WIDTH);",
                  "}", ""]

    lines += [
        "static inline int64_t dmctp_sign_extend(uint64_t value, unsigned width)",
        "{", "    const uint64_t sign = UINT64_C(1) << (width - 1u);",
        "    return (int64_t)((value ^ sign) - sign);", "}", ""
    ]
    for fmt_name, fmt in formats.items():
        imm = fmt.get("imm")
        if not imm:
            continue
        terms, width = [], 0
        if "bits" in imm:
            msb, lsb = imm["bits"]
            shift = imm.get("shift", 0)
            terms.append(f"((uint64_t)dmctp_field(inst, {lsb}u, {msb-lsb+1}u) << {shift}u)")
            width = (msb - lsb + 1) + shift
        else:
            for part in imm["parts"]:
                sms, sls = part["src"]
                dms, dls = part["dst"]
                terms.append(f"((uint64_t)dmctp_field(inst, {sls}u, {sms-sls+1}u) << {dls}u)")
                width = max(width, dms + 1)
        expr = " | ".join(terms)
        lines += [f"static inline uint64_t dmctp_uimm_{fmt_name}(uint32_t inst)", "{",
                  f"    return {expr};", "}", "",
                  f"static inline int64_t dmctp_imm_{fmt_name}(uint32_t inst)", "{",
                  f"    const uint64_t value = dmctp_uimm_{fmt_name}(inst);"]
        lines.append(f"    return dmctp_sign_extend(value, {width}u);" if imm.get("signed") else "    return (int64_t)value;")
        lines += ["}", ""]

    lines += [
        "static inline const dmctp_instruction_desc_t *dmctp_decode(uint32_t inst)",
        "{", "    size_t i;", "    for (i = 0; i < DMCTP_INSTRUCTION_COUNT; ++i) {",
        "        const dmctp_instruction_desc_t *desc = &dmctp_instruction_table[i];",
        "        if ((inst & desc->mask) == desc->match) return desc;", "    }",
        "    return NULL;", "}", "", "#endif", ""
    ]
    return "\n".join(lines)


def emit_section(title):
    bar = "/" * 72
    return f"  // {bar}\n  // {title}\n  // {bar}\n\n"

